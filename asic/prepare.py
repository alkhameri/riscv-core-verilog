#!/usr/bin/env python3
"""Convert the synthesizable SV to Verilog and record the exact source inputs."""
import hashlib
import json
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parents[1]
sources = [line.strip() for line in (root / "rtl/files.f").read_text().splitlines() if line.strip()]
output = root / "build/asic"
output.mkdir(parents=True, exist_ok=True)
version = subprocess.check_output(["sv2v", "--version"], text=True).strip()
verilog = output / "rv32_core.v"
with verilog.open("w") as stream:
    # sv2v emits explicit truncating casts, sign-extended constants, an ascending
    # helper vector, and flattened structs with unused fields. Keep these waivers
    # on generated code only; the source RTL still passes make lint without them.
    stream.write("// Generated by sv2v from rtl/files.f. Do not edit.\n")
    for warning in ("WIDTH", "LITENDIAN", "UNUSEDSIGNAL"):
        stream.write(f"/* verilator lint_off {warning} */\n")
    stream.flush()
    subprocess.run(
        ["sv2v", "--define=SYNTHESIS", "--top=rv32_core", *sources],
        cwd=root, stdout=stream, check=True,
    )
manifest = {
    "converter": version,
    "sources": {name: hashlib.sha256((root / name).read_bytes()).hexdigest() for name in sources},
    "generated_verilog_sha256": hashlib.sha256(verilog.read_bytes()).hexdigest(),
}
(output / "sources.json").write_text(json.dumps(manifest, indent=2) + "\n")
print(f"Converted {len(sources)} files with {version}: {verilog.relative_to(root)}")
